package rules

import "github.com/NotChaosuu/vibecheck/internal/model"

func injectionRules() []Rule {
	return []Rule{
		{
			ID: "sql-string-interpolation", Title: "SQL query built by string interpolation",
			Severity: model.High, Confidence: model.Review,
			OWASP:   "A03:2021 Injection",
			Detail:  "A SQL statement passed to a query call is assembled with an interpolated value instead of a parameter. If any part is user-controlled this is SQL injection.",
			Fix:     "Use a parameterized query with placeholders ($1 / ? / %s) and an args list.",
			Exts:    []string{".js", ".jsx", ".ts", ".tsx", ".py", ".go", ".mjs", ".cjs"},
			Pattern: mustRE("(?i)(\\.(query|execute|raw|prepare)\\s*\\(\\s*`[^`]*\\b(select|insert|update|delete)\\b[^`]*\\$\\{|(^|[^.\\w])sql`[^`]*\\$\\{)"),
		},
		{
			ID: "sql-fstring-interpolation", Title: "SQL query built with an f-string",
			Severity: model.High, Confidence: model.Review,
			OWASP:   "A03:2021 Injection",
			Detail:  "A SQL statement passed to execute() is built with a Python f-string that interpolates a value. If it is user-controlled this is SQL injection.",
			Fix:     "Pass parameters to the driver: cursor.execute(sql, (value,)).",
			Exts:    []string{".py"},
			Pattern: mustRE(`(?i)(execute|executemany|executescript|raw)\s*\(\s*f["'][^"']*\b(select|insert|update|delete)\b[^"']*\{`),
		},
		{
			ID: "command-shell-true", Title: "Subprocess spawned with shell=True",
			Severity: model.Critical, Confidence: model.Confirmed,
			OWASP:   "A03:2021 Injection",
			Detail:  "A subprocess is run with shell=True, so the command string is interpreted by the shell. Any interpolated value can inject commands.",
			Fix:     "Pass an argument list and drop shell=True: subprocess.run([\"ls\", path]).",
			Exts:    []string{".py"},
			Pattern: mustRE(`(?i)subprocess\.(run|call|check_output|Popen)\s*\([^)]*shell\s*=\s*True`),
		},
		{
			ID: "command-exec-dynamic", Title: "Shell command built from a dynamic string",
			Severity: model.High, Confidence: model.Review,
			OWASP:   "A03:2021 Injection",
			Detail:  "A command is passed to os.system / child_process.exec built from a variable or template. If any part is user-controlled this is command injection.",
			Fix:     "Use an args array with execFile/spawn (Node) or a list with shell=False (Python).",
			Exts:    []string{".py", ".js", ".jsx", ".ts", ".tsx", ".mjs", ".cjs"},
			Pattern: mustRE("(os\\.system\\s*\\(|child_process\\.exec\\s*\\(|(^|[^.\\w])exec\\s*\\(\\s*`)"),
			Allow:   reList(`execFile`, `\.exec\(\s*["'][^"']*["']\s*\)`),
		},
		{
			ID: "eval-dynamic-input", Title: "eval / new Function on a non-literal value",
			Severity: model.High, Confidence: model.Review,
			OWASP:   "A03:2021 Injection",
			Detail:  "eval / new Function is called with something other than a constant string. If the input is user-controlled this is remote code execution.",
			Fix:     "Use a real parser: JSON.parse for data, a lookup table for dynamic dispatch.",
			Exts:    []string{".js", ".jsx", ".ts", ".tsx", ".mjs", ".cjs"},
			Pattern: mustRE(`(\beval\s*\(\s*[^'")\s]|new\s+Function\s*\()`),
			Allow:   reList(`\.eval\s*\(`, `function\s+eval\b`),
		},
		{
			ID: "python-eval-exec", Title: "eval / exec on a non-literal value",
			Severity: model.High, Confidence: model.Review,
			OWASP:   "A03:2021 Injection",
			Detail:  "Python's eval / exec runs whatever string it's given. If the input is user-controlled this is remote code execution.",
			Fix:     "Use ast.literal_eval for literals, or a real parser. Never eval untrusted input.",
			Exts:    []string{".py"},
			Pattern: mustRE(`(^|[^.\w])(eval|exec)\s*\(\s*[^'")\s]`),
			Allow:   reList(`\bdef\s+(eval|exec)\b`, `\.eval\s*\(`, `\.exec\s*\(`),
		},
		{
			ID: "pickle-loads", Title: "Untrusted data deserialized with pickle",
			Severity: model.Critical, Confidence: model.Confirmed,
			OWASP:   "A08:2021 Software & Data Integrity Failures",
			Detail:  "pickle.load/loads executes arbitrary code during deserialization. On any data you didn't produce yourself, this is remote code execution.",
			Fix:     "Use JSON for untrusted data. Reserve pickle for data you fully control.",
			Exts:    []string{".py"},
			Pattern: mustRE(`pickle\.loads?\s*\(`),
		},
		{
			ID: "yaml-unsafe-load", Title: "YAML parsed with an unsafe loader",
			Severity: model.High, Confidence: model.Confirmed,
			OWASP:   "A08:2021 Software & Data Integrity Failures",
			Detail:  "yaml.load without SafeLoader (or yaml.unsafe_load) can construct arbitrary Python objects, allowing code execution on crafted input.",
			Fix:     "Use yaml.safe_load(...) instead.",
			Exts:    []string{".py"},
			Pattern: mustRE(`(yaml\.unsafe_load\s*\(|yaml\.load\s*\()`),
			Allow:   reList(`SafeLoader`, `safe_load`),
		},
		{
			ID: "weak-hash", Title: "Weak hash algorithm (MD5 / SHA1)",
			Severity: model.Medium, Confidence: model.Review,
			OWASP:   "A02:2021 Cryptographic Failures",
			Detail:  "MD5 and SHA1 are broken for security use. If this hashes passwords or tokens it's a real weakness.",
			Fix:     "Use bcrypt/argon2 for passwords and SHA-256+ for integrity.",
			Pattern: mustRE(`(?i)(createHash\s*\(\s*['"]md5['"]|createHash\s*\(\s*['"]sha1['"]|hashlib\.md5\s*\(|hashlib\.sha1\s*\(|md5\.New\s*\(|sha1\.New\s*\()`),
		},
		{
			ID: "open-redirect", Title: "Redirect target from user input",
			Severity: model.Medium, Confidence: model.Review,
			OWASP:   "A01:2021 Broken Access Control",
			Detail:  "A redirect destination comes straight from the request. Attackers can send users to a phishing origin.",
			Fix:     "Allow only relative paths or an explicit host allowlist for redirect targets.",
			Exts:    []string{".js", ".jsx", ".ts", ".tsx", ".py"},
			Pattern: mustRE(`(?i)(res\.redirect\s*\(\s*req\.(query|params|body)|redirect\s*\(\s*request\.(args|GET|values))`),
		},
	}
}
